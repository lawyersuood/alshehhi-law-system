// ============================================================
// إعادة التصنيف الجماعي (Bulk Reclassification) — القيود والدفاتر
// أداة لتصحيح تصنيف عدة أسطر قيود دفعة واحدة: نقلها من حساب لآخر في شجرة الحسابات
// (مثال: مصروفات سُجّلت بالخطأ في "مصروفات متنوعة" ويُراد نقلها لحساب "قرطاسية")
// بدل فتح كل قيد وتعديله يدوياً واحداً تلو الآخر. كل عملية إعادة تصنيف تُسجَّل في
// سجل تدقيق (Log) دائم يوضح متى ومن ومن أي حساب لأي حساب ولأي قيود، للشفافية.
// ============================================================

export interface BulkReclassLogEntry {
  id: string;
  date: string; // تاريخ تنفيذ العملية (وقت الإعادة، ليس تاريخ القيود نفسها)
  fromAccountId: string;
  toAccountId: string;
  entryIds: string[]; // معرّفات القيود التي تأثرت
  linesCount: number; // عدد الأسطر التي أُعيد تصنيفها
  totalAmount: number; // إجمالي المبلغ المنقول (مدين + دائن)
  performedBy?: string;
  createdAt: string;
}

export const BULK_RECLASS_LS_KEYS = {
  log: "firm_accounting_bulk_reclass_log_v1",
};
